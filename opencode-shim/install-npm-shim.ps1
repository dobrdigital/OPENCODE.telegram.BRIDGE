<#
.SYNOPSIS
    Points the npm `opencode` entry points at the compatibility shim.

.DESCRIPTION
    Why this exists
    ---------------
    cc-connect v1.5.0 calls OpenCode in two ways OpenCode 2.0.28 rejects:
      opencode run --dir <workDir>   -> "Unrecognized flag: --dir"
      opencode session list --json   -> wants --format json, exits 1

    opencode-shim.js fixes both. But it must be reached through the npm
    entry point, because cc-connect resolves the binary via
    exec.LookPath("opencode") - the `cmd` array in config.toml is not used
    for session operations (opencode.go:654 passes only the binary element).

    So: replace both npm launchers with a delegation to the shim.

    Idempotent. Run it after any `npm update` or `npm i -g @opencode/cli`,
    which regenerates the originals and silently undoes the patch.

.PARAMETER Verify
    Check the wiring without changing anything. Exit 1 if a call site is
    broken. Useful as a health check.

.PARAMETER Restore
    Put the original npm launchers back.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install-npm-shim.ps1 -Verify

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install-npm-shim.ps1
#>

[CmdletBinding()]
param(
    [switch] $Verify,
    [switch] $Restore
)

$ErrorActionPreference = 'Stop'

$npmBin    = Join-Path $env:APPDATA 'npm'
$shim      = Join-Path $PSScriptRoot 'opencode-shim.js'
$node      = (Get-Command node.exe -ErrorAction SilentlyContinue).Source
if (-not $node) { $node = '<NODE>' }

$CmdFile   = Join-Path $npmBin 'opencode.cmd'
$ShFile    = Join-Path $npmBin 'opencode'
$CmdBackup = "$CmdFile.orig-backup"
$ShBackup  = "$ShFile.orig-backup"

# ── verify ──────────────────────────────────────────────────────────────
if ($Verify) {
    $bad = 0

    # A machine without OpenCode has nothing to be wired. Reporting MISSING
    # launchers there turns "this runner has no npm install" into a red
    # build, which is the same mistake as asking a question nobody could
    # answer and treating the silence as a no. Say so and pass.
    $launchers = @($CmdFile, $ShFile) | Where-Object { Test-Path -LiteralPath $_ }
    if ($launchers.Count -eq 0) {
        Write-Host ''
        Write-Host 'SKIPPED  no npm opencode launcher on this machine - nothing to verify.' -ForegroundColor DarkGray
        Write-Host '         Install it with: npm install -g @opencode/cli' -ForegroundColor DarkGray
        exit 0
    }

    foreach ($f in @($CmdFile, $ShFile)) {
        if (-not (Test-Path -LiteralPath $f)) { Write-Host "MISSING  $f"; $bad++; continue }
        $text = Get-Content -LiteralPath $f -Raw
        if ($text -notlike "*opencode-shim.js*") {
            Write-Host "BYPASSED $f  (does not reference the shim)"
            $bad++
        }
        else {
            Write-Host "OK       $f"
        }
    }

    if (-not (Test-Path -LiteralPath $shim)) { Write-Host "MISSING  $shim"; $bad++ }

    if ($bad -eq 0) {
        Write-Host ''
        Write-Host 'Wiring intact.' -ForegroundColor Green
        exit 0
    }

    Write-Host ''
    Write-Host "$bad problem(s). Run without -Verify to repair." -ForegroundColor Red
    exit 1
}

# ── restore ─────────────────────────────────────────────────────────────
if ($Restore) {
    foreach ($pair in @(@($CmdFile, $CmdBackup), @($ShFile, $ShBackup))) {
        $target, $backup = $pair
        if (Test-Path -LiteralPath $backup) {
            Copy-Item -LiteralPath $backup -Destination $target -Force
            Write-Output ("restored {0}" -f $target)
        }
        else {
            Write-Warning "no backup for $target"
        }
    }
    Write-Output 'run `npm i -g @opencode/cli` if the originals are still wrong.'
    exit 0
}

# ── patch ───────────────────────────────────────────────────────────────
if (-not (Test-Path -LiteralPath $shim)) {
    Write-Error "shim not found: $shim"
    exit 1
}
if (-not (Test-Path -LiteralPath $node)) {
    Write-Error "node.exe not found at $node"
    exit 1
}

$cmdBody = @(
    '@ECHO off'
    'REM Routed through the cc-connect/OpenCode compatibility shim.'
    'REM Regenerated by any `npm i -g @opencode/cli`; re-run install-npm-shim.ps1'
    'SETLOCAL'
    ('"{0}" "{1}" %*' -f $node, $shim)
) -join "`r`n"

$shBody = @(
    '#!/bin/sh'
    '# Routed through the cc-connect/OpenCode compatibility shim.'
    '# Regenerated by any `npm i -g @opencode/cli`; re-run install-npm-shim.ps1'
    ('exec "{0}" "{1}" "$@"' -f $node, $shim)
) -join "`n"

foreach ($spec in @(
    @{ Path = $CmdFile; Backup = $CmdBackup; Body = $cmdBody; Mode = 'cmd' }
    @{ Path = $ShFile;  Backup = $ShBackup;  Body = $shBody;  Mode = 'sh'  }
)) {
    $p = $spec.Path
    if (-not (Test-Path -LiteralPath $p)) {
        Write-Warning "not found, skipping: $p"
        continue
    }

    $current = Get-Content -LiteralPath $p -Raw
    if ($current -like '*opencode-shim.js*') {
        Write-Output ("already wired: {0}" -f $p)
        continue
    }

    if (-not (Test-Path -LiteralPath $spec.Backup)) {
        Copy-Item -LiteralPath $p -Destination $spec.Backup -Force
        Write-Output ("backed up {0}" -f $spec.Backup)
    }

    if ($spec.Mode -eq 'cmd') {
        [System.IO.File]::WriteAllText($p, $spec.Body, (New-Object System.Text.ASCIIEncoding))
    }
    else {
        [System.IO.File]::WriteAllText($p, $spec.Body, (New-Object System.Text.UTF8Encoding($false)))
    }

    Write-Output ("patched   {0}" -f $p)
}

Write-Host ''
& $PSCommandPath -Verify
exit $LASTEXITCODE